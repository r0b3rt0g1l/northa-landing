export const getAsistente = porIdioma((locale) => {
  const servicios = getServicios(locale);
  const seguridad = getSeguridad(locale);
  const contexto = {
    servicios,
    seguridad,
    sistemas: servicios.find((s) => s.id === "portales-sistemas"),
    total: getProyectoDestacado(locale)?.enlaces?.length ?? 0,
    correo: site.contact.email,
    porId: (id) => servicios.find((s) => s.id === id)?.description ?? "",
  };

  const temas = localizar(temasBase, locale).map((t) => ({
    ...t,
    respuesta: typeof t.respuesta === "function" ? t.respuesta(contexto) : t.respuesta,
  }));

  return { asistente: localizar(asistenteBase, locale), temas };
});
